//! Generates `crates/libobs-sys/src/bindings.rs` from the OBS headers (D-01).
//!
//! Kept out of the workspace so that building the plugin needs neither
//! libclang nor the headers. Run it through `scripts/gen-libobs-bindings.sh`,
//! which finds the headers and formats the result like `cargo fmt`.
//!
//! Only the API the plugin uses is generated: a short, reviewable file whose
//! diff shows what an OBS upgrade changes for the plugin, and nothing else.

use std::env;
use std::process::ExitCode;

use bindgen::{EnumVariation, Formatter, RustEdition, RustTarget};

/// Functions the plugin calls. The types they take and return follow them.
const FUNCTIONS: &[&str] = &[
    // Module, locale and log.
    "blog",
    "obs_module_load_locale",
    "text_lookup_getstr",
    "text_lookup_destroy",
    "obs_register_source_s",
    // Settings.
    "obs_data_get_bool",
    "obs_data_get_int",
    "obs_data_get_string",
    "obs_data_set_default_bool",
    "obs_data_set_default_int",
    "obs_data_set_default_string",
    // Properties.
    "obs_properties_create",
    "obs_properties_add_bool",
    "obs_properties_add_int",
    "obs_property_int_set_suffix",
    "obs_properties_add_color_alpha",
    "obs_properties_add_text",
    "obs_properties_add_list",
    "obs_property_list_add_string",
    "obs_properties_add_group",
    // Drawing a premultiplied sRGB texture, as OBS's own image source does.
    "obs_enter_graphics",
    "obs_leave_graphics",
    "gs_texture_create",
    "gs_texture_destroy",
    "gs_effect_get_param_by_name",
    "gs_effect_set_texture_srgb",
    "gs_blend_state_push",
    "gs_blend_function",
    "gs_blend_state_pop",
    "gs_draw_sprite",
    "gs_framebuffer_srgb_enabled",
    "gs_enable_framebuffer_srgb",
    // Drawing a window of a scrolling text's strip at its line.
    "gs_draw_sprite_subregion",
    "gs_matrix_push",
    "gs_matrix_pop",
    "gs_matrix_translate3f",
];

/// Constants no function signature pulls in: macros and anonymous enums.
const VARS: &[&str] = &[
    "LIBOBS_API_MAJOR_VER",
    "LIBOBS_API_MINOR_VER",
    "LIBOBS_API_PATCH_VER",
    "LOG_ERROR",
    "LOG_WARNING",
    "LOG_INFO",
    "LOG_DEBUG",
    "OBS_SOURCE_VIDEO",
    "OBS_SOURCE_SRGB",
];

/// Types that `obs_source_info` reaches only through callbacks the plugin
/// leaves unset. Opaque, they keep their size and alignment for the layout
/// of `obs_source_info` without dragging in the audio, video and input APIs.
const OPAQUE: &[&str] = &[
    "obs_source_frame",
    "obs_audio_data",
    "obs_source_audio_mix",
    "audio_output_data",
    "obs_mouse_event",
    "obs_key_event",
];

fn main() -> ExitCode {
    let args: Vec<String> = env::args().skip(1).collect();
    let [include_dir, output] = args.as_slice() else {
        eprintln!("usage: gen-libobs-bindings <obs-include-dir> <output.rs>");
        return ExitCode::FAILURE;
    };
    match generate(include_dir, output) {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("gen-libobs-bindings: {error}");
            ExitCode::FAILURE
        }
    }
}

fn generate(include_dir: &str, output: &str) -> Result<(), Box<dyn std::error::Error>> {
    let builder = bindgen::Builder::default()
        .header_contents("wrapper.h", "#include <obs-module.h>\n")
        .clang_arg(format!("-I{include_dir}"))
        .rust_target(RustTarget::stable(87, 0).map_err(|e| e.to_string())?)
        .rust_edition(RustEdition::Edition2024)
        // Plain constants: a Rust enum would be undefined behaviour the day
        // OBS hands back a value this version does not know.
        .default_enum_style(EnumVariation::Consts)
        .prepend_enum_name(false)
        // Zeroed like a C designated initializer, so a callback table names
        // only the callbacks it sets.
        .derive_default(true)
        .formatter(Formatter::None)
        .raw_line("// Generated by tools/gen-libobs-bindings, do not edit.")
        .raw_line("// Regenerate with scripts/gen-libobs-bindings.sh.");
    let builder = FUNCTIONS
        .iter()
        .fold(builder, |b, name| b.allowlist_function(name));
    let builder = VARS.iter().fold(builder, |b, name| b.allowlist_var(name));
    let builder = OPAQUE.iter().fold(builder, |b, name| b.opaque_type(name));
    builder.generate()?.write_to_file(output)?;
    Ok(())
}
